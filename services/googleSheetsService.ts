import { DailyReport, InspectionStatus } from '../types';
import { getOrCreateInspectionFolder, moveFileToFolder } from './googleDriveService';

export interface GoogleSpreadsheetResult {
  spreadsheetId: string;
  spreadsheetUrl: string;
  title: string;
  folderId?: string;
  folderUrl?: string;
  driveViewUrl?: string;
}

/**
 * Membuat Google Spreadsheet di Google Drive pengguna untuk laporan inspeksi LP
 * dan menempatkannya ke dalam folder 'Laporan Inspeksi LP BU Banten'
 */
export async function uploadInspectionToGoogleSheets(
  report: DailyReport,
  accessToken: string
): Promise<GoogleSpreadsheetResult> {
  const storeName = report.store || 'Toko BU Banten';
  const cleanDate = report.date.replace(/[/\\?%*:|"<>]/g, '-');
  const title = `Laporan LP - ${storeName} - ${cleanDate}`;

  // 1. Buat Spreadsheet baru dengan 3 sheet tab
  const createResponse = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      properties: {
        title,
      },
      sheets: [
        {
          properties: {
            title: 'Ringkasan Laporan',
            gridProperties: { rowCount: 40, columnCount: 8 },
          },
        },
        {
          properties: {
            title: 'Checklist Items',
            gridProperties: { rowCount: 60, columnCount: 6 },
          },
        },
        {
          properties: {
            title: 'Temuan Observasi',
            gridProperties: { rowCount: 40, columnCount: 6 },
          },
        },
      ],
    }),
  });

  if (!createResponse.ok) {
    const errorData = await createResponse.json().catch(() => ({}));
    throw new Error(
      errorData.error?.message || `Gagal membuat spreadsheet (Status: ${createResponse.status})`
    );
  }

  const spreadsheetData = await createResponse.json();
  const spreadsheetId = spreadsheetData.spreadsheetId;
  const spreadsheetUrl = `https://docs.google.com/spreadsheets/d/${spreadsheetId}/edit`;

  // 2. Siapkan data value untuk setiap sheet
  const passCount = report.items.filter((i) => i.status === InspectionStatus.PASS).length;
  const failCount = report.items.filter((i) => i.status === InspectionStatus.FAIL).length;
  const naCount = report.items.filter((i) => i.status === InspectionStatus.NA).length;

  // Sheet 1: Ringkasan Laporan
  const summaryValues = [
    ['LAPORAN INSPEKSI HARIAN LOSS PREVENTION BU BANTEN', ''],
    ['Generated by Sistem Inspeksi LP Digital', ''],
    ['', ''],
    ['INFORMASI UMUM', ''],
    ['Toko / Store', storeName],
    ['Nama LP Supervisor', report.lpSupervisor || '-'],
    ['NIK Supervisor', report.nik || '-'],
    ['Tanggal Inspeksi', report.date],
    ['Compliance Score (Kepatuhan)', `${report.complianceScore}%`],
    ['', ''],
    ['STATISTIK PEMERIKSAAN', ''],
    ['Item PASS (Sesuai Standar)', passCount],
    ['Item FAIL (Temuan Masalah)', failCount],
    ['Item N/A (Tidak Ada / Terpasang)', naCount],
    ['Total Temuan Observasi', report.observations.length],
    ['', ''],
    ['RINGKASAN & ANALISIS LP AI', ''],
    [report.aiSummary || 'Tidak ada catatan ringkasan otomatis.', ''],
  ];

  // Sheet 2: Checklist Items
  const checklistHeader = ['No', 'Kategori', 'Item Pemeriksaan Standar LP', 'Status', 'Catatan / Nilai Expired'];
  const checklistValues = [
    checklistHeader,
    ...report.items.map((item, idx) => [
      idx + 1,
      item.category,
      item.label,
      item.status || 'BELUM DIPERIKSA',
      item.value ? `Nilai: ${item.value}` : (item.comment || '-'),
    ]),
  ];

  // Sheet 3: Temuan Observasi
  const obsHeader = ['No', 'Area / Lokasi Temuan', 'Tingkat Risiko (Severity)', 'Waktu', 'Deskripsi Masalah & Rekomendasi'];
  const obsValues = [
    obsHeader,
    ...(report.observations.length > 0
      ? report.observations.map((obs, idx) => [
          idx + 1,
          obs.location,
          obs.severity,
          obs.timestamp,
          obs.description,
        ])
      : [['-', 'Tidak ada temuan anomali/observasi pada inspeksi ini.', '-', '-', '-']]),
  ];

  // 3. Masukkan data ke sheet via batchUpdate values
  const updateValuesResponse = await fetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values:batchUpdate`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        valueInputOption: 'USER_ENTERED',
        data: [
          {
            range: "'Ringkasan Laporan'!A1:B18",
            values: summaryValues,
          },
          {
            range: `'Checklist Items'!A1:E${checklistValues.length}`,
            values: checklistValues,
          },
          {
            range: `'Temuan Observasi'!A1:E${obsValues.length}`,
            values: obsValues,
          },
        ],
      }),
    }
  );

  if (!updateValuesResponse.ok) {
    console.warn('Gagal mengisi data spreadsheet values, namun file telah dibuat di Drive');
  }

  // 4. Styling dan visual formatting
  try {
    const sheet1Id = spreadsheetData.sheets?.[0]?.properties?.sheetId || 0;
    const sheet2Id = spreadsheetData.sheets?.[1]?.properties?.sheetId || 1;
    const sheet3Id = spreadsheetData.sheets?.[2]?.properties?.sheetId || 2;

    await fetch(`https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}:batchUpdate`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        requests: [
          // Judul Utama Sheet 1
          {
            repeatCell: {
              range: { sheetId: sheet1Id, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 2 },
              cell: {
                userEnteredFormat: {
                  backgroundColor: { red: 0.12, green: 0.23, blue: 0.54 },
                  textFormat: { foregroundColor: { red: 1, green: 1, blue: 1 }, bold: true, fontSize: 13 },
                },
              },
              fields: 'userEnteredFormat(backgroundColor,textFormat)',
            },
          },
          // Header Checklist Sheet 2
          {
            repeatCell: {
              range: { sheetId: sheet2Id, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 5 },
              cell: {
                userEnteredFormat: {
                  backgroundColor: { red: 0.15, green: 0.38, blue: 0.92 },
                  textFormat: { foregroundColor: { red: 1, green: 1, blue: 1 }, bold: true },
                },
              },
              fields: 'userEnteredFormat(backgroundColor,textFormat)',
            },
          },
          // Header Observasi Sheet 3
          {
            repeatCell: {
              range: { sheetId: sheet3Id, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 5 },
              cell: {
                userEnteredFormat: {
                  backgroundColor: { red: 0.79, green: 0.15, blue: 0.15 },
                  textFormat: { foregroundColor: { red: 1, green: 1, blue: 1 }, bold: true },
                },
              },
              fields: 'userEnteredFormat(backgroundColor,textFormat)',
            },
          },
          // Auto resize column widths
          {
            autoResizeDimensions: {
              dimensions: { sheetId: sheet2Id, dimension: 'COLUMNS', startIndex: 0, endIndex: 5 },
            },
          },
          {
            autoResizeDimensions: {
              dimensions: { sheetId: sheet3Id, dimension: 'COLUMNS', startIndex: 0, endIndex: 5 },
            },
          },
        ],
      }),
    });
  } catch (styleErr) {
    console.warn('Styling spreadsheet skipped:', styleErr);
  }

  let folderId: string | undefined;
  let folderUrl: string | undefined;
  let driveViewUrl: string | undefined;

  try {
    const folderRes = await getOrCreateInspectionFolder(accessToken);
    folderId = folderRes.id;
    folderUrl = folderRes.webViewLink;

    const moveRes = await moveFileToFolder(spreadsheetId, folderId, accessToken);
    if (moveRes.webViewLink) {
      driveViewUrl = moveRes.webViewLink;
    }
  } catch (folderErr) {
    console.warn('Gagal menata folder Google Drive:', folderErr);
  }

  return {
    spreadsheetId,
    spreadsheetUrl,
    title,
    folderId,
    folderUrl,
    driveViewUrl,
  };
}
